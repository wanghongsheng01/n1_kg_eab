"""Enterprise case (de-identified ERP): paper/numbers_erp.tex and results/erp_summary.md from results/erp_outcomes.csv.

The outcome records are produced by code/export_erp_outcomes.py and hold no question text, query, answer or identifier.
"""
import csv, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SUBS = ["sql", "sql_u", "cypher", "cypher_u", "semantic", "classify", "agent"]
SN = {"sql": "SQL", "sql_u": "SQLU", "cypher": "GraphT", "cypher_u": "GraphU", "semantic": "Metric", "classify": "MetricR", "agent": "Agent"}
R = list(csv.DictReader(open(os.path.join(HERE, "results", "erp_outcomes.csv"))))
for r in R:
    r["correct"] = r["correct"] == "1"
COV = {r["qid"]: r["metric_covered"] == "1" for r in R}
R = [r for r in R if r["rep"] in ("", "0")]
mac, md = {}, ["| substrate | runs | acc % | silent % of failures | out-cov refused | agent raw-SQL share |", "|---|---|---|---|---|---|"]
for s in SUBS:
    rs = [r for r in R if r["substrate"] == s]
    if not rs:
        continue
    a = sum(r["correct"] for r in rs) / len(rs)
    f = [r for r in rs if not r["correct"]]
    sil = sum(r["outcome"] == "wrong" for r in f)
    o = [r for r in rs if not COV.get(r["qid"], True)]
    ref = sum(r["outcome"] == "abstain" for r in o)
    byp = (sum(r.get("route") == "fallback" for r in rs) / len(rs)) if s == "agent" else None
    mac[f"Erp{SN[s]}Acc"] = f"{100 * a:.0f}"
    mac[f"Erp{SN[s]}Silent"] = f"{100 * sil / len(f):.0f}" if f else "--"
    if s in ("semantic", "classify"):
        mac[f"Erp{SN[s]}OutRefused"] = f"{ref}/{len(o)}"
    if byp is not None:
        mac["ErpAgentBypass"] = f"{100 * byp:.0f}"
    md.append(f"| {s} | {len(rs)} | {100 * a:.0f} | {mac[f'Erp{SN[s]}Silent']} | {ref}/{len(o)} | {'' if byp is None else f'{100 * byp:.0f}'} |")
# paired differences, bootstrap over templates as in the main analysis (B=20000)
import random
from collections import defaultdict
ix = {(r["model"], r["substrate"], r["qid"]): r for r in R}
for a, b, k in (("cypher", "sql", "GraphTSQL"), ("sql_u", "cypher_u", "SQLUGraphU"), ("sql_u", "sql", "SQLUSQL")):
    pc = defaultdict(list)
    for (m, s_, q), r in ix.items():
        if s_ == a and (m, b, q) in ix:
            pc[r["tpl"]].append((int(r["correct"]), int(ix[(m, b, q)]["correct"])))
    cl, rng = list(pc.values()), random.Random(1)
    d = lambda cs: sum(x - y for c in cs for x, y in c) / sum(len(c) for c in cs)
    bs = sorted(d([rng.choice(cl) for _ in cl]) for _ in range(20000))
    mac[f"ErpEff{k}"], mac[f"ErpEffLo{k}"], mac[f"ErpEffHi{k}"] = (f"{100 * v:.0f}" for v in (d(cl), bs[500], bs[19499]))
mac["ErpQuestions"] = str(len({r["qid"] for r in R}))
mac["ErpRuns"] = f"{len(R):,}"
open(os.path.join(HERE, "results", "erp_summary.md"), "w").write("\n".join(md) + "\n")
with open(os.path.join(HERE, "paper", "numbers_erp.tex"), "w") as fo:
    fo.write("% generated by code/analyze_erp.py from de-identified enterprise runs (aggregates only)\n")
    for k, v in sorted(mac.items()):
        fo.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print("\n".join(md))
